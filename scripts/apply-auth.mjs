// Switches AI KRISH from the shared passcode to real sign-in.
// It checks EVERY expected line first. If anything is missing it stops and changes nothing.
// Originals are saved next to each file as <name>.bak-auth.
import fs from "node:fs";

const read = (p) => fs.readFileSync(p, "utf8");
const jobs = []; // { file, text }
const problems = [];
const count = (s, sub) => s.split(sub).length - 1;

function edit(file, fn) {
  if (!fs.existsSync(file)) { problems.push(`${file}: file not found`); return; }
  const before = read(file);
  const after = fn(before, (msg) => problems.push(`${file}: ${msg}`));
  if (after !== null && after !== before) jobs.push({ file, before, text: after });
}
function swap(src, from, to, fail, expected = 1) {
  const n = count(src, from);
  if (n !== expected) { fail(`expected ${expected}x but found ${n}x of: ${from.slice(0, 70).replace(/\n/g, "\\n")}`); return src; }
  return src.split(from).join(to);
}

// chat route
edit("app/api/chat/route.ts", (s, fail) => {
  if (s.includes("requireUser")) return null;
  s = swap(s, `import { callOpenAICompat, hasKey, type ChatMsg } from "../../../lib/chatProviders";`,
    `import { callOpenAICompat, hasKey, type ChatMsg } from "../../../lib/chatProviders";\nimport { requireUser } from "../../../lib/auth";`, fail);
  return swap(s, `  const need = process.env.APP_PASSCODE;
  if (need && req.headers.get("x-krish-pass") !== need) {
    return Response.json({ error: "locked" }, { status: 401 });
  }`, `  const session = await requireUser();
  if (!session.ok) {
    return Response.json({ error: session.error }, { status: session.status });
  }`, fail);
});

// analyze route
edit("app/api/analyze/route.ts", (s, fail) => {
  if (s.includes("requireUser")) return null;
  s = swap(s, `import { authorize, clientKey, rateLimit } from "../../../lib/security";`,
    `import { clientKey, rateLimit } from "../../../lib/security";\nimport { requireUser } from "../../../lib/auth";`, fail);
  return swap(s, `  // 1. Access control. Wrong passcodes are throttled so they cannot be guessed quickly.
  const auth = authorize(req);
  if (!auth.ok) {
    if (auth.status === 401) {
      const t = rateLimit("authfail:" + ip, 10, 60_000);
      if (!t.ok) return json({ error: "Too many wrong passcodes. Wait a minute." }, 429, { "Retry-After": String(t.retryAfter) });
    }
    return json({ error: auth.error }, auth.status);
  }`, `  // 1. Access control: a signed-in, email-verified user is required.
  const session = await requireUser();
  if (!session.ok) return json({ error: session.error }, session.status);`, fail);
});

// read-only data routes
for (const f of ["signal", "candles", "assets"]) {
  edit(`app/api/${f}/route.ts`, (s, fail) => {
    if (s.includes("requireUser")) return null;
    const re = /export async function GET\([^)]*\)[^{]*\{\n/;
    if (!re.test(s)) { fail("could not find `export async function GET(...) {`"); return s; }
    s = s.replace(re, (m) => m + `  const session = await requireUser();\n  if (!session.ok) return Response.json({ error: session.error }, { status: session.status });\n`);
    return `import { requireUser } from "../../../lib/auth";\n` + s;
  });
}

// main page
edit("app/page.tsx", (s, fail) => {
  if (s.includes("LogoutButton")) return null;
  s = swap(s, `headers: { "Content-Type": "application/json", "x-krish-pass": (() => { try { return localStorage.getItem("krish-pass") ?? ""; } catch { return ""; } })() },`,
    `headers: { "Content-Type": "application/json" },`, fail);
  s = swap(s, `      xhr.setRequestHeader("x-krish-pass", passcode());\n`, ``, fail);
  s = swap(s, `setLocked(true);`, `window.location.assign("/login");`, fail, 2);
  s = swap(s, `import { DEFAULT_LIMITS } from "../lib/files/limits";`,
    `import { DEFAULT_LIMITS } from "../lib/files/limits";\nimport LogoutButton from "../components/LogoutButton";`, fail);
  return swap(s, `      {locked && (`, `      <LogoutButton />\n\n      {locked && (`, fail);
});

// page title (optional)
edit("app/layout.tsx", (s) => s.replace(`title: "Create Next App"`, `title: "AI KRISH"`).replace(`description: "Generated by create next app"`, `description: "Your personal AI assistant."`));

// .env.example placeholders
const envLines = `\n# Sign-in (Supabase). Placeholders only. Real values go in .env.local and Vercel.\nNEXT_PUBLIC_SUPABASE_URL=\nNEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=\n`;
edit(".env.example", (s) => (s.includes("NEXT_PUBLIC_SUPABASE_URL") ? s : s.replace(/\n*$/, "\n") + envLines));

if (problems.length) {
  console.error("STOPPED. Nothing was changed. Send me this list:\n- " + problems.join("\n- "));
  process.exit(1);
}
for (const j of jobs) {
  fs.writeFileSync(j.file + ".bak-auth", j.before);
  fs.writeFileSync(j.file, j.text);
  console.log("updated", j.file);
}
console.log(jobs.length ? "\nDone. Backups end in .bak-auth." : "Nothing to change (already applied).");
